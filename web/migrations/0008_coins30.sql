-- 0008_coins30.sql — 기본 코인 20 → 30 (2026-09-07 사용자 결정, 동생 피드백).
--
-- 라운드당 최대 3코인 × 10라운드 = 30 이다. 20 으로 시작하면 7라운드째에 지갑이 비고
-- 남은 세 라운드는 힌트를 받아도 걸 것이 없다 — 정답을 좁혀 놓고 아무것도 못 하는
-- 라운드가 게임의 끝에 붙는다.
--
-- ⚠️ INSERT 가 아니라 **UPDATE** 다 (0005 와 같은 이유). 0002 가 이미 initialCoins 행을
--    넣어 뒀고, INSERT OR IGNORE 로는 이미 있는 행의 값을 못 바꾼다 — 조용히 아무 일도
--    안 일어나서 "코드는 30인데 배포판은 20으로 도는" 상태가 된다. `src/game/config.ts`
--    의 DEFAULTS 는 이 행이 없을 때(새 D1)만 쓰인다.
--
-- ⚠️ 여기서는 **덮는 것이 목적**이다. 선생님이 관리 화면에서 일부러 20 으로 바꿔 뒀다면
--    이 마이그레이션이 그것도 30 으로 되돌린다. 20 은 리뉴얼 전(5~6라운드) 시절의 값이라
--    지금 규칙에서는 되돌릴 값이 아니라고 보았다.

UPDATE settings SET value = '30' WHERE key = 'initialCoins';
